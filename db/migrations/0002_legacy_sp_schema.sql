    l_tags varchar(4000) := null;
BEGIN
    if TG_OP = 'INSERT' then
        NEW.created := statement_timestamp();
        NEW.created_by := coalesce(coalesce(current_setting('evs.app_user', true), current_user),user);
    end if;
    NEW.updated := statement_timestamp();
    NEW.updated_by := coalesce(coalesce(current_setting('evs.app_user', true), current_user),user);
    --
    --
    --
    NEW.tags := upper(NEW.tags);
    --
    -- touch parent table
    --
    update sp_release_trains set updated = statement_timestamp(), updated_by = NEW.updated_by where id = NEW.release_id;
    --
    -- adjust tag data
    --
    if (NEW.tags IS NOT NULL AND NEW.tags::text <> '') then
        l_tags := trim(both upper(NEW.tags));
        -- remove multiple spaces
        if position('  ' in l_tags) > 0 then
            for j in 1..10 loop
                l_tags := replace(l_tags,'  ',' ');
                if position('  ' in l_tags) = 0 then
                   exit;
                end if;
            end loop;
        end if;
        for i in 1..length(l_tags) loop
            if i > 2 and substr(l_tags,i,1) = ' ' and substr(l_tags,i-1,1) != ',' then
               l_tags := substr(l_tags,1,i-1)||'-'||substr(l_tags,i+1);
            end if;
        end loop;
        NEW.tags := l_tags;
   end if;
    --
    -- history
    --
    if TG_OP = 'INSERT' then
        insert into sp_release_history(release_id, attribute_column, change_type, new_value, changed_on, changed_by)
        values (NEW.release_id, 'DOCUMENT', 'CREATE', NEW.DOCUMENT_FILENAME, statement_timestamp(), lower(NEW.created_by));
    elsif TG_OP = 'UPDATE' then
        insert into sp_release_history(release_id, attribute_column, change_type, old_value, new_value, changed_on, changed_by)
        values (NEW.release_id, 'DOCUMENT', 'UPDATE', OLD.DOCUMENT_FILENAME, NEW.DOCUMENT_FILENAME, statement_timestamp(), lower(NEW.updated_by));
    end if;
RETURN NEW;
end
