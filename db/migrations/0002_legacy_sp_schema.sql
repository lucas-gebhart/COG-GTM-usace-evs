CREATE SCHEMA IF NOT EXISTS sp_util;
CREATE OR REPLACE FUNCTION sp_util.compress_int(n bigint) RETURNS text LANGUAGE plpgsql IMMUTABLE AS $$
DECLARE ret text := ''; quotient bigint := n; remainder integer;
BEGIN
  WHILE quotient > 0 LOOP
    remainder := quotient % 36; quotient := quotient / 36;
    ret := CASE WHEN remainder < 26 THEN chr(ascii('A') + remainder) ELSE chr(ascii('0') + remainder - 26) END || ret;
  END LOOP;
  IF length(ret) < 5 THEN ret := lpad(ret, 4, 'A'); END IF;
  RETURN upper(ret);
END $$;
