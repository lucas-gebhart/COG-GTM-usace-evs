-- Oracle instr(str, sub, start) used by the document views (ora2pg ships the same helper in its orafce notes).
CREATE OR REPLACE FUNCTION legacy.instr(str text, sub text, start_pos integer DEFAULT 1)
RETURNS integer LANGUAGE plpgsql IMMUTABLE AS $$
DECLARE pos integer; len integer; BEGIN
  IF start_pos > 0 THEN
    pos := position(sub IN substr(str, start_pos)); RETURN CASE WHEN pos = 0 THEN 0 ELSE pos + start_pos - 1 END;
  ELSIF start_pos < 0 THEN
    len := length(str);
    FOR i IN REVERSE (len + start_pos + 1)..1 LOOP
      IF substr(str, i, length(sub)) = sub THEN RETURN i; END IF;
    END LOOP;
    RETURN 0;
  END IF;
  RETURN 0;
END $$;
-- Oracle NUMBER locals arrive as numeric; PostgreSQL will not implicitly cast them for substr/instr
CREATE OR REPLACE FUNCTION legacy.substr(str text, start_pos numeric) RETURNS text
LANGUAGE sql IMMUTABLE AS $$ SELECT substr(str, start_pos::integer) $$;
CREATE OR REPLACE FUNCTION legacy.substr(str text, start_pos numeric, len numeric) RETURNS text
LANGUAGE sql IMMUTABLE AS $$ SELECT substr(str, start_pos::integer, len::integer) $$;
CREATE OR REPLACE FUNCTION legacy.instr(str text, sub text, start_pos numeric) RETURNS integer
LANGUAGE sql IMMUTABLE AS $$ SELECT legacy.instr(str, sub, start_pos::integer) $$;
